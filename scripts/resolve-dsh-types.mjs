#!/usr/bin/env node
/**
 * Resolve the INSTALLED DeepSeek Harness type declarations for TypeScript.
 *
 * This writes a gitignored `tsconfig.dsh.json` that maps `@deepseek-ai/*` to
 * the harness own `.d.ts` files, and NOTHING ELSE. It creates no symlink and
 * writes nothing outside this repository.
 *
 * Why not a devDependency? The published DSH packages disagree with each other
 * on peer ranges (dsh-agent@0.1.5-rc.1 -> dsh-session-projection@^0.1.5-rc.1 ->
 * dsh-session@^0.1.5-rc.2, while the harness ships 0.1.5-rc.1), so npm refuses
 * to resolve the tree.
 *
 * Mapping is also MORE correct than installing: the plugin is type-checked
 * against exactly the version it runs on.
 *
 * SAFETY: an earlier revision of this workflow symlinked the harness packages
 * into this project node_modules. A later `npm install` followed the link and
 * pruned ~240 packages out of the global harness install. Read-only path
 * mapping cannot do that, so it is the only mechanism used here.
 *
 * Harness location resolution order:
 *   1. --dsh <path>   (harness package dir, or its node_modules)
 *   2. $DSH_PACKAGE
 *   3. the dsh executable on PATH
 *   4. a globally installed @deepseek-ai/dsh
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function candidateManifests() {
  const candidates = [];
  const flagIndex = process.argv.indexOf('--dsh');
  if (flagIndex !== -1 && process.argv[flagIndex + 1]) {
    const given = resolve(process.argv[flagIndex + 1]);
    candidates.push(join(given, 'package.json'));
    candidates.push(join(given, 'node_modules', '@deepseek-ai', 'dsh', 'package.json'));
  }
  if (process.env.DSH_PACKAGE) {
    candidates.push(join(resolve(process.env.DSH_PACKAGE), 'package.json'));
  }
  try {
    const bin = execFileSync('readlink', ['-f', execFileSync('which', ['dsh'], { encoding: 'utf8' }).trim()], { encoding: 'utf8' }).trim();
    if (bin) candidates.push(join(dirname(dirname(bin)), 'package.json'));
  } catch {
    /* dsh is not on PATH */
  }
  try {
    candidates.push(createRequire(import.meta.url).resolve('@deepseek-ai/dsh/package.json'));
  } catch {
    /* not resolvable from here */
  }
  return candidates;
}

const manifest = candidateManifests().find((candidate) => existsSync(candidate));
if (!manifest) {
  console.error('resolve-dsh-types: could not locate a DeepSeek Harness install.');
  console.error('  Pass --dsh <path>, set DSH_PACKAGE, or put dsh on PATH.');
  process.exit(1);
}

const harnessRoot = dirname(manifest);
const scopeDir = join(harnessRoot, 'node_modules', '@deepseek-ai');
if (!existsSync(scopeDir)) {
  console.error(`resolve-dsh-types: ${scopeDir} does not exist -- is the harness fully installed?`);
  process.exit(1);
}

const { version } = JSON.parse(readFileSync(manifest, 'utf8'));
// TypeScript does NOT consult a mapped directory package.json exports under
// NodeNext: a `paths` target that is a directory is probed for index.*, so
// mapping '@deepseek-ai/*' to the package dirs resolves nothing. Map to the
// declaration ENTRY FILE instead. 237 of the harness 240 scoped packages use
// `lib/types/index.d.ts`; the three that do not are the web frontend and the
// native addons, none of which appear in the harness type graph.
const scopePosix = scopeDir.split('\\').join('/');
const entry = (suffix) => scopePosix + '/*/' + suffix;
const output = {
  // GENERATED by scripts/resolve-dsh-types.mjs -- do not edit, do not commit.
  compilerOptions: {
    baseUrl: '.',
    paths: {
      '@deepseek-ai/*/types': [entry('lib/types/index.d.ts')],
      '@deepseek-ai/*': [entry('lib/types/index.d.ts')],
    },
  },
};
const outFile = join(projectRoot, 'tsconfig.dsh.json');
writeFileSync(outFile, JSON.stringify(output, null, 2) + String.fromCharCode(10));
console.log(`resolve-dsh-types: mapped @deepseek-ai/* from dsh ${version}`);
console.log(`  -> ${scopeDir}/*`);
console.log(`  wrote ${outFile}`);